"""Generate the Notepad++ User Defined Language files from ../spec.

Usage: python build.py [--check]

With --check, nothing is written; the exit status is 1 if a file is out of date.
"""

import os
import sys
from xml.sax.saxutils import escape

HERE = os.path.dirname(os.path.abspath(__file__))
SPEC = os.path.join(HERE, '..', 'spec')

LANGUAGES = [
    # file stem, UDL name, extension, keyword list
    ('SysML-v2', 'SysML v2', 'sysml', 'sysml-keywords.txt'),
    ('KerML', 'KerML', 'kerml', 'kerml-keywords.txt'),
]

# Light: the colours of the SysML v2 Pilot Implementation's Eclipse editor.
# Dark: the Java colours of Notepad++'s DarkModeDefault theme.
PALETTES = {
    'light': dict(fg='000000', bg='FFFFFF', keyword='7F0055',
                  comment='3F7F5F', string='2A00FF'),
    'dark': dict(fg='DCDCCC', bg='3F3F3F', keyword='DFC47D',
                 comment='7F9F7F', string='CC9393'),
}

# Single-character operators; braces are fold markers instead.
OPERATORS = '( ) [ ] ; , ~ @ % & ^ | * + - / $ . : < = > ? !'

# Block comment //* */ (a multiline note) is tried before the line comment //.
COMMENTS = '00// 01 02 03//* 04*/'

# 1: strings, 2: unrestricted names, 3: regular comments /* */ (bodies).
DELIMITERS = ('00" 01\\ 02((" EOL)) 03\' 04\\ 05((\' EOL)) 06/* 07 08*/ '
              + ' '.join('%02d' % i for i in range(9, 24)))

KEYWORD_LISTS = [
    'Comments', 'Numbers, prefix1', 'Numbers, prefix2', 'Numbers, extras1',
    'Numbers, extras2', 'Numbers, suffix1', 'Numbers, suffix2',
    'Numbers, range', 'Operators1', 'Operators2', 'Folders in code1, open',
    'Folders in code1, middle', 'Folders in code1, close',
    'Folders in code2, open', 'Folders in code2, middle',
    'Folders in code2, close', 'Folders in comment, open',
    'Folders in comment, middle', 'Folders in comment, close',
] + ['Keywords%d' % i for i in range(1, 9)] + ['Delimiters']

STYLES = (['DEFAULT', 'COMMENTS', 'LINE COMMENTS', 'NUMBERS']
          + ['KEYWORDS%d' % i for i in range(1, 9)]
          + ['OPERATORS', 'FOLDER IN CODE1', 'FOLDER IN CODE2',
             'FOLDER IN COMMENT']
          + ['DELIMITERS%d' % i for i in range(1, 9)])


def read_keywords(name):
    with open(os.path.join(SPEC, name), encoding='utf-8') as f:
        return [line.strip() for line in f
                if line.strip() and not line.startswith('#')]


def style_of(name, palette):
    """(colour, bold) for a style; colour None means the theme's colours."""
    if name in ('KEYWORDS1', 'KEYWORDS2'):
        return palette['keyword'], True
    if name in ('COMMENTS', 'LINE COMMENTS'):
        return palette['comment'], False
    if name in ('DELIMITERS1', 'DELIMITERS3'):
        return palette['string'], False
    return None, False


def udl(name, ext, keywords, variant):
    palette = PALETTES[variant]
    lists = {
        'Comments': COMMENTS,
        'Operators1': OPERATORS,
        'Folders in code1, open': '{',
        'Folders in code1, close': '}',
        'Keywords1': ' '.join(keywords),
        'Keywords2': '#',
        'Delimiters': DELIMITERS,
    }
    dark = ' darkModeTheme="yes"' if variant == 'dark' else ''
    lines = [
        '<?xml version="1.0" encoding="UTF-8" ?>',
        '<!-- Generated by build.py from the keyword lists in ../spec. -->',
        '<NotepadPlus>',
        '    <UserLang name="%s" ext="%s"%s udlVersion="2.1">' % (name, ext, dark),
        '        <Settings>',
        '            <Global caseIgnored="no" allowFoldOfComments="no" '
        'foldCompact="no" forcePureLC="0" decimalSeparator="0" />',
        '            <Prefix Keywords1="no" Keywords2="yes" Keywords3="no" '
        'Keywords4="no" Keywords5="no" Keywords6="no" Keywords7="no" '
        'Keywords8="no" />',
        '        </Settings>',
        '        <KeywordLists>',
    ]
    for key in KEYWORD_LISTS:
        lines.append('            <Keywords name="%s">%s</Keywords>'
                     % (key, escape(lists.get(key, ''))))
    lines += ['        </KeywordLists>', '        <Styles>']
    for style in STYLES:
        colour, bold = style_of(style, palette)
        lines.append(
            '            <WordsStyle name="%s" fgColor="%s" bgColor="%s" '
            'colorStyle="%d" fontStyle="%d" nesting="0" />'
            % (style, colour or palette['fg'], palette['bg'],
               1 if colour else 0, 1 if bold else 0))
    lines += ['        </Styles>', '    </UserLang>', '</NotepadPlus>', '']
    return '\n'.join(lines)


def files():
    for stem, name, ext, keyword_file in LANGUAGES:
        keywords = read_keywords(keyword_file)
        yield stem + '.udl.xml', udl(name, ext, keywords, 'light')
        yield stem + '.dark.udl.xml', udl(name + ' (dark)', ext, keywords,
                                          'dark')


def main(check):
    stale = []
    for filename, content in files():
        path = os.path.join(HERE, filename)
        if check:
            try:
                with open(path, encoding='utf-8') as f:
                    current = f.read()
            except FileNotFoundError:
                current = None
            if current != content:
                stale.append(filename)
        else:
            with open(path, 'w', encoding='utf-8', newline='\n') as f:
                f.write(content)
    if stale:
        print('Out of date: ' + ', '.join(stale))
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main('--check' in sys.argv[1:]))
